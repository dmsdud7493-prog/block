/** "뭐야/뭐예요/무엇/뜻/이란/모르겠" 같은 개념 질문인지 */
const CONCEPT_Q = /(뭐야|뭐예요|뭔가요|뭐에요|뭐지|무엇인가요|무엇이에요|무엇일까|뜻|의미|이란|란\s*\?|란 뭐|가 뭐|이 뭐|는 뭐|은 뭐|설명해|알려\s*줘|모르겠)/;

/** 답·결과·수치를 달라는 질문은 개념 질문이 아니다 → 예측 먼저 규칙으로 (지침 3.1) */
const ASKS_ANSWER = /(답|결과|얼마|몇|같아\?|달라\?|그래프)/;

export function conceptOf(text: string): GlossaryEntry | null {
  if (!CONCEPT_Q.test(text) || ASKS_ANSWER.test(text)) return null;
  // 더 긴(구체적인) 용어를 먼저 본다 — "통제 변인"이 "변인"보다 먼저
  const hits = GLOSSARY.flatMap((g) => g.terms.filter((t) => text.includes(t)).map((t) => ({ g, len: t.length })));
  if (hits.length === 0) return null;
  return hits.reduce((a, b) => (b.len > a.len ? b : a)).g;
}
