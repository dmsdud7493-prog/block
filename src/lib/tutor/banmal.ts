/**
 * 해요체 → 친절한 반말 — 다른 화면과 같이 쓰는 안내 문장(계산 칸 오류 힌트·개념 사전)을 랩메이트가 말할 때만 바꾼다.
 * 문장 끝 어미만 바꾸는 단순 규칙이라 랩메이트가 쓰는 문장 모양에 맞춰 두었다(tests/unit/tutor/banmal.test.ts).
 */
const RULES: [RegExp, string][] = [
  [/볼까요\?/g, "볼까?"],
  [/할까요\?/g, "할까?"],
  [/일까요\?/g, "일까?"],
  [/을까요\?/g, "을까?"],
  [/까요\?/g, "까?"],
  [/무엇인가요\?/g, "뭐야?"],
  [/인가요\?/g, "이야?"],
  [/나눠요/g, "나눠"],
  [/보세요/g, "봐"],
  [/주세요/g, "줘"],
  [/하세요/g, "해"],
  [/이에요/g, "이야"],
  [/예요/g, "야"],
  [/있어요/g, "있어"],
  [/없어요/g, "없어"],
  [/했어요/g, "했어"],
  [/됐어요/g, "됐어"],
  [/왔어요/g, "왔어"],
  [/맞았어요/g, "맞았어"],
  [/아니에요/g, "아니야"],
  [/해요/g, "해"],
  [/돼요/g, "돼"],
  [/써요/g, "써"],
  [/나와요/g, "나와"],
  [/읽어요/g, "읽어"],
  [/줘요/g, "줘"],
  [/봐요/g, "봐"],
  [/어요/g, "어"],
  [/아요/g, "아"],
  [/워요/g, "워"],
];

export function toBanmal(text: string): string {
  return RULES.reduce((t, [re, to]) => t.replace(re, to), text);
}
